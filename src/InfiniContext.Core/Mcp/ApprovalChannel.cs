using System.Diagnostics;
using System.IO.Pipes;
using System.Runtime.InteropServices;
using System.Runtime.Versioning;
using System.Security.AccessControl;
using System.Security.Principal;
using System.Text;
using System.Text.Json.Nodes;
using InfiniContext.Core.Mcp.Sessions;
using InfiniContext.Core.Mcp.Tasks;
using Serilog;

namespace InfiniContext.Core.Mcp;

/// <summary>
/// Host-side IPC for the approval flow. Listens on a per-session named pipe; for each connected
/// sidecar reads tagged JSON lines, dispatches to <see cref="IApprovalSink"/> (default kind) or
/// <see cref="LockRegistry"/> (Phase 7 <c>lock.*</c> kinds), and writes the response back. NDJSON,
/// one request/response per line.
///
/// The pipe name is generated by <see cref="GeneratePipeName"/> and embedded in the
/// <c>--mcp-config</c> JSON so the sidecar can connect back. Each <see cref="ApprovalChannel"/>
/// accepts exactly one connection — one channel instance per claude session — so the
/// host's session manager (Stage 2) creates N channels for N parallel sessions.
///
/// <para>
/// When a <see cref="LockRegistry"/> is supplied, the pipe name doubles as the lock owner id:
/// every lock acquired through this channel is released on dispose, so a session that exits
/// (clean or crashed) cannot strand a lock past its own lifetime.
/// </para>
/// </summary>
public sealed class ApprovalChannel : IAsyncDisposable
{
    private readonly string _pipeName;
    private readonly IApprovalSink _sink;
    private readonly LockRegistry? _lockRegistry;
    private readonly TimeSpan _lockTtl;
    private readonly TimeSpan _lockMaxWait;
    private readonly Func<SessionExitRequest, CancellationToken, Task>? _onSessionExit;
    private readonly string? _expectedClientExecutable;
    private readonly ILogger _logger;
    private readonly TimeSpan _disposeTimeout;
    private readonly CancellationTokenSource _cts = new();
    private Task? _serverTask;
    private NamedPipeServerStream? _pipe;
    private int _disposed;

    public ApprovalChannel(
        string pipeName,
        IApprovalSink sink,
        ILogger? logger = null,
        int disposeTimeoutSeconds = 2,
        LockRegistry? lockRegistry = null,
        TimeSpan? lockTtl = null,
        TimeSpan? lockMaxWait = null,
        Func<SessionExitRequest, CancellationToken, Task>? onSessionExit = null,
        string? expectedClientExecutable = null)
    {
        _pipeName = pipeName;
        _sink = sink;
        _lockRegistry = lockRegistry;
        _lockTtl = lockTtl ?? TimeSpan.FromSeconds(30);
        _lockMaxWait = lockMaxWait ?? TimeSpan.FromSeconds(60);
        _onSessionExit = onSessionExit;
        // M1: the image the connecting sidecar is expected to run. The sidecar is a re-spawn of the
        // host's own executable (claude launches "<our exe> --mcp-approval-server <pipe>"), so the
        // default is this process's image. The launcher passes the resolved sidecar path explicitly
        // in case ApprovalSidecarExecutable is ever overridden.
        _expectedClientExecutable = expectedClientExecutable ?? Environment.ProcessPath;
        _logger = logger ?? Log.Logger;
        _disposeTimeout = TimeSpan.FromSeconds(disposeTimeoutSeconds);
    }

    public string PipeName => _pipeName;

    // Keep the suffix short: on macOS, .NET maps a named pipe to a Unix domain socket at
    // `$TMPDIR/CoreFxPipe_<name>`, and the UDS `sun_path` limit is 104 chars. $TMPDIR on macOS
    // is typically `/var/folders/<2>/<28>/T/` (~50 chars) + `CoreFxPipe_` (11) = ~61 chars of
    // unavoidable prefix, leaving ~43 chars for the pipe name. The 23-char `infinicontext-approval-`
    // prefix + a 12-hex-char id = 35 chars, comfortably inside the budget; 12 hex chars (48 bits)
    // is far more than needed for per-host uniqueness across concurrent sessions.
    public static string GeneratePipeName() => $"infinicontext-approval-{Guid.NewGuid():N}"[..35];

    /// <summary>
    /// Begins listening. The returned task signals when the listener has reached the
    /// <c>WaitForConnection</c> state — call this BEFORE spawning claude so the sidecar
    /// can connect immediately.
    /// </summary>
    public Task StartAsync()
    {
        _pipe = CreatePipe();
        _serverTask = Task.Run(RunServerAsync);
        return Task.CompletedTask;
    }

    /// <summary>
    /// Create the server pipe. On Windows (M1) the pipe's ACL is restricted to the current user so
    /// no other account on a shared machine can connect; if applying the ACL fails for any reason we
    /// log and fall back to the default (the client-identity check below is the same-user guard). On
    /// Unix the pipe maps to a Unix-domain socket under <c>$TMPDIR</c> whose directory permissions
    /// already scope it to the current user, and <c>PipeSecurity</c> is unsupported there.
    /// </summary>
    private NamedPipeServerStream CreatePipe()
    {
        if (OperatingSystem.IsWindows())
        {
            var secured = TryCreateCurrentUserPipe();
            if (secured is not null) return secured;
        }

        return new NamedPipeServerStream(
            _pipeName,
            PipeDirection.InOut,
            maxNumberOfServerInstances: 1,
            PipeTransmissionMode.Byte,
            PipeOptions.Asynchronous);
    }

    [SupportedOSPlatform("windows")]
    private NamedPipeServerStream? TryCreateCurrentUserPipe()
    {
        try
        {
            using var identity = WindowsIdentity.GetCurrent();
            var user = identity.User;
            if (user is null) return null;

            var security = new PipeSecurity();
            security.AddAccessRule(new PipeAccessRule(user, PipeAccessRights.FullControl, AccessControlType.Allow));

            return NamedPipeServerStreamAcl.Create(
                _pipeName,
                PipeDirection.InOut,
                maxNumberOfServerInstances: 1,
                PipeTransmissionMode.Byte,
                PipeOptions.Asynchronous,
                inBufferSize: 0,
                outBufferSize: 0,
                security);
        }
        catch (Exception ex)
        {
            _logger.Warning(ex, "approval-channel: could not apply current-user pipe ACL; using default security");
            return null;
        }
    }

    /// <summary>
    /// M1 peer authentication. Returns false only when we can confidently establish that the
    /// connected client process is NOT the expected sidecar executable; every inconclusive case
    /// (non-Windows, PID/image unresolvable, expected image unknown) returns true so a legitimate
    /// connection is never dropped. Windows-only enforcement today: the client PID comes from
    /// <c>GetNamedPipeClientProcessId</c> and we compare its image path to the expected sidecar.
    /// </summary>
    private bool ClientIsTrusted()
    {
        if (!OperatingSystem.IsWindows()) return true;
        if (string.IsNullOrEmpty(_expectedClientExecutable)) return true;

        uint clientPid;
        try
        {
            var handle = _pipe!.SafePipeHandle.DangerousGetHandle();
            if (!GetNamedPipeClientProcessId(handle, out clientPid)) return true; // can't resolve → allow
        }
        catch (Exception ex)
        {
            _logger.Debug(ex, "approval-channel: client PID lookup failed; allowing connection");
            return true;
        }

        try
        {
            using var clientProc = Process.GetProcessById((int)clientPid);
            var clientImage = clientProc.MainModule?.FileName;
            if (string.IsNullOrEmpty(clientImage)) return true; // access-denied / cross-arch → allow

            if (string.Equals(clientImage, _expectedClientExecutable, StringComparison.OrdinalIgnoreCase))
                return true;

            _logger.Warning(
                "approval-channel: rejecting connection from unexpected client image={ClientImage} pid={Pid}; expected={Expected}",
                clientImage, clientPid, _expectedClientExecutable);
            return false;
        }
        catch (Exception ex)
        {
            // The process may have exited between connect and lookup, or MainModule may be
            // inaccessible. Inconclusive → allow (the ACL still bounds cross-user access).
            _logger.Debug(ex, "approval-channel: client image lookup inconclusive for pid={Pid}; allowing", clientPid);
            return true;
        }
    }

    [SupportedOSPlatform("windows")]
    [DllImport("kernel32.dll", SetLastError = true)]
    [return: MarshalAs(UnmanagedType.Bool)]
    private static extern bool GetNamedPipeClientProcessId(nint pipe, out uint clientProcessId);

    private async Task RunServerAsync()
    {
        // Re-listen loop (M13): a single accept used to mean that if the sidecar died and `claude`
        // respawned its MCP server (normal MCP recovery), the new sidecar had nothing to connect
        // to — every gated tool call errored or hung silently for the rest of the session. After a
        // connection ends we Disconnect() and WaitForConnection() again so a respawned sidecar
        // reconnects. A failure to even accept (or to reset the pipe) stops the listener rather
        // than busy-looping.
        while (!_cts.IsCancellationRequested)
        {
            try
            {
                _logger.Debug("approval-channel: waiting for connection on pipe={PipeName}", _pipeName);
                await _pipe!.WaitForConnectionAsync(_cts.Token).ConfigureAwait(false);
            }
            catch (OperationCanceledException) { break; }
            catch (Exception ex)
            {
                _logger.Error(ex, "approval-channel: WaitForConnection failed; listener stopping");
                break;
            }

            _logger.Debug("approval-channel: sidecar connected");

            // M1: authenticate the connected peer before serving it. The threat is the processes
            // this approval flow gates — any tool the agent spawns runs as the same user and could
            // otherwise connect to forge lock ops, send session.exit, or flood prompts. We refuse a
            // connection whose client image is confidently NOT the expected sidecar executable.
            // Best-effort: an inconclusive check (non-Windows, unresolvable PID/image) allows the
            // connection — the ACL above already bounds cross-user access.
            if (!ClientIsTrusted())
            {
                try { if (_pipe!.IsConnected) _pipe.Disconnect(); } catch { /* fall through to re-listen */ }
                continue;
            }

            try
            {
                await ServeConnectionAsync().ConfigureAwait(false);
            }
            catch (OperationCanceledException) { break; }
            catch (IOException ex) { _logger.Debug("approval-channel: pipe closed ({Reason})", ex.Message); }
            catch (Exception ex) { _logger.Error(ex, "approval-channel: server loop crashed during serve"); }

            if (_cts.IsCancellationRequested) break;

            try
            {
                if (_pipe!.IsConnected) _pipe.Disconnect();
                _logger.Warning("approval-channel: sidecar disconnected; re-listening on pipe={PipeName}", _pipeName);
            }
            catch (Exception ex)
            {
                _logger.Warning(ex, "approval-channel: could not reset pipe for re-listen; listener stopping");
                break;
            }
        }
    }

    /// <summary>Serve one connected sidecar until its stream reaches EOF (the sidecar disconnects).</summary>
    private async Task ServeConnectionAsync()
    {
        using var reader = new StreamReader(_pipe!, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false), leaveOpen: true);
        await using var writer = new StreamWriter(_pipe!, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false), bufferSize: -1, leaveOpen: true)
        {
            AutoFlush = true,
            NewLine = "\n",
        };

        string? line;
        while ((line = await reader.ReadLineAsync(_cts.Token).ConfigureAwait(false)) is not null)
        {
            if (line.Length == 0) continue;

            JsonObject? requestObj;
            try
            {
                requestObj = JsonNode.Parse(line) as JsonObject;
            }
            catch (Exception ex)
            {
                _logger.Warning("approval-channel: malformed request line: {Reason}", ex.Message);
                continue;
            }

            if (requestObj is null)
            {
                _logger.Warning("approval-channel: non-object request line ignored");
                continue;
            }

            var kind = requestObj[LockWireFormat.KindField]?.GetValue<string>() ?? LockWireFormat.ApprovalKind;
            JsonObject responseJson;
            switch (kind)
            {
                case LockWireFormat.AcquireKind:
                    responseJson = (await HandleLockAcquireAsync(requestObj).ConfigureAwait(false)).ToJson();
                    break;
                case LockWireFormat.ReleaseKind:
                    responseJson = HandleLockRelease(requestObj).ToJson();
                    break;
                case LockWireFormat.SessionExitKind:
                    responseJson = HandleSessionExit(requestObj).ToJson();
                    break;
                case LockWireFormat.ApprovalKind:
                    responseJson = (await HandleApprovalAsync(requestObj).ConfigureAwait(false)).ToWireJson();
                    break;
                default:
                    // Unknown discriminator: a future sidecar emitting a new kind against an
                    // older host. Refuse explicitly rather than misinterpreting as approval.
                    _logger.Warning("approval-channel: unknown message kind={Kind}, replying with error", kind);
                    responseJson = new JsonObject
                    {
                        ["error"] = $"unknown kind: {kind}",
                    };
                    break;
            }

            await writer.WriteLineAsync(responseJson.ToJsonString()).ConfigureAwait(false);
        }
    }

    private async Task<ApprovalResponse> HandleApprovalAsync(JsonObject obj)
    {
        var sw = System.Diagnostics.Stopwatch.StartNew();
        try
        {
            var request = ApprovalRequest.FromJson(obj);
            _logger.Information("approval: request tool={Tool}", request.ToolName);
            var response = await _sink.RequestAsync(request, _cts.Token).ConfigureAwait(false);
            sw.Stop();
            _logger.Information(
                "approval: response behavior={Behavior} latency={LatencyMs}ms",
                response.Behavior, sw.ElapsedMilliseconds);
            return response;
        }
        catch (Exception ex)
        {
            sw.Stop();
            _logger.Error(
                ex,
                "approval-channel: sink threw after {LatencyMs}ms, defaulting to deny",
                sw.ElapsedMilliseconds);
            return ApprovalResponse.Deny($"host error: {ex.Message}");
        }
    }

    private async Task<LockAcquireResponse> HandleLockAcquireAsync(JsonObject obj)
    {
        if (_lockRegistry is null)
            return LockAcquireResponse.Failed("lock subsystem unavailable");
        try
        {
            var req = LockAcquireRequest.FromJson(obj);
            // M2: the wire-supplied owner id is NOT trusted. The owner is always this channel's pipe
            // name so that (a) dispose-time ReleaseAllOwnedBy(_pipeName) reclaims every lock this
            // session took, and (b) a release can be authenticated against the acquiring channel. A
            // sidecar that sets some other owner string can no longer strand a lock past our dispose.
            var outcome = await _lockRegistry.AcquireAsync(req.FilePath, _pipeName, _lockTtl, _lockMaxWait, _cts.Token).ConfigureAwait(false);
            return outcome.Ok
                ? LockAcquireResponse.Granted(outcome.Token!, (int)outcome.TtlGranted.TotalSeconds)
                : LockAcquireResponse.Failed(outcome.Error ?? "unknown error");
        }
        catch (OperationCanceledException)
        {
            return LockAcquireResponse.Failed("host shutting down");
        }
        catch (Exception ex)
        {
            _logger.Error(ex, "approval-channel: lock.acquire handler threw");
            return LockAcquireResponse.Failed($"host error: {ex.Message}");
        }
    }

    private LockReleaseResponse HandleLockRelease(JsonObject obj)
    {
        if (_lockRegistry is null) return new LockReleaseResponse(false);
        try
        {
            var req = LockReleaseRequest.FromJson(obj);
            // M2: authenticate the release against this channel's owner id. A connection that holds
            // or guesses a token owned by a different session cannot release it.
            return new LockReleaseResponse(_lockRegistry.Release(req.Token, _pipeName));
        }
        catch (Exception ex)
        {
            _logger.Error(ex, "approval-channel: lock.release handler threw");
            return new LockReleaseResponse(false);
        }
    }

    private SessionExitResponse HandleSessionExit(JsonObject obj)
    {
        if (_onSessionExit is null)
        {
            // A newer skill emitting session.exit against a host that wired no handler. Refuse
            // explicitly (the sidecar surfaces ok:false as a tool error) rather than hanging.
            _logger.Warning("approval-channel: session.exit received but no handler wired");
            return new SessionExitResponse(false);
        }
        try
        {
            var req = SessionExitRequest.FromJson(obj);
            // Fire-and-forget is load-bearing: the agent's tool result must return BEFORE stdin
            // closes, or claude may die before reading it. Deferring the close to the threadpool
            // lets this method reply {ok:true} on the pipe first. See design.md §"Sequence diagram".
            _ = Task.Run(() => _onSessionExit(req, _cts.Token));
            return new SessionExitResponse(true);
        }
        catch (Exception ex)
        {
            _logger.Error(ex, "approval-channel: session.exit handler threw");
            return new SessionExitResponse(false);
        }
    }

    public async ValueTask DisposeAsync()
    {
        if (Interlocked.Exchange(ref _disposed, 1) == 1) return;

        // Reclaim any locks owned by this channel BEFORE tearing down the pipe so a session that
        // crashed mid-edit can never strand a lock past its own lifetime.
        if (_lockRegistry is not null)
        {
            try { _lockRegistry.ReleaseAllOwnedBy(_pipeName); } catch { /* best-effort */ }
        }

        try { _cts.Cancel(); } catch { }
        if (_pipe is not null)
        {
            try { _pipe.Dispose(); } catch { }
        }
        if (_serverTask is not null)
        {
            try { await _serverTask.WaitAsync(_disposeTimeout).ConfigureAwait(false); } catch { }
        }
        // If WaitAsync timed out (a sink is hung), the server loop may still hold _cts.Token.
        // Disposing the CTS while it's in use would throw ObjectDisposedException — swallow that
        // narrow case so a tighter outer catch in future doesn't surface a confusing crash.
        try { _cts.Dispose(); } catch (ObjectDisposedException) { }
    }
}
