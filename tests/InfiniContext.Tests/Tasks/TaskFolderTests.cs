    [Fact]
    public async Task CopyArtifacts_preserves_mtimes_and_creates_destination()
    {
        using var tmp = new TempDir();
        var src = new TaskFolder(tmp.Path, 1, "source");
        await src.EnsureExistsAsync(Today, TestContext.Current.CancellationToken);
        // Stamp known mtimes.
        var fixedTime = new DateTime(2025, 12, 31, 12, 0, 0, DateTimeKind.Utc);
        File.SetLastWriteTimeUtc(Path.Combine(src.Path, "index.md"), fixedTime);
        File.SetLastWriteTimeUtc(Path.Combine(src.Path, "progress.md"), fixedTime);

        var dst = new TaskFolder(tmp.Path, 2, "fork");
        await src.CopyArtifactsToAsync(dst, TestContext.Current.CancellationToken);

        Directory.Exists(dst.Path).Should().BeTrue();
        File.Exists(Path.Combine(dst.Path, "index.md")).Should().BeTrue();
        File.GetLastWriteTimeUtc(Path.Combine(dst.Path, "index.md")).Should().Be(fixedTime);
        File.GetLastWriteTimeUtc(Path.Combine(dst.Path, "progress.md")).Should().Be(fixedTime);
    }

