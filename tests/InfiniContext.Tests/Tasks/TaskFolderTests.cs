    private static readonly DateOnly Today = new(2026, 5, 7);

    [Fact]
    public void Path_is_composed_via_Path_Combine()
    {
        using var tmp = new TempDir();
        var folder = new TaskFolder(tmp.Path, 42, "implement-phase-two");

        folder.Name.Should().Be("0042-implement-phase-two");
        folder.Path.Should().Be(Path.Combine(tmp.Path, ".task", "0042-implement-phase-two"));
    }

    [Theory]
    [InlineData(0)]
    [InlineData(-3)]
    public void Constructor_rejects_non_positive_id(int badId)
    {
        var act = () => new TaskFolder("C:/work", badId, "slug");
        act.Should().Throw<ArgumentOutOfRangeException>();
    }

    [Theory]
    [InlineData(null)]
    [InlineData("")]
    [InlineData("  ")]
    public void Constructor_rejects_blank_inputs(string? value)
    {
        // null → ArgumentNullException, blank/whitespace → ArgumentException; both derive from ArgumentException.
        ((Action)(() => new TaskFolder(value!, 1, "slug"))).Should().Throw<ArgumentException>();
        ((Action)(() => new TaskFolder("C:/work", 1, value!))).Should().Throw<ArgumentException>();
    }

    [Fact]
    public async Task EnsureExists_creates_folder_with_three_mandatory_scaffolds()
    {
        using var tmp = new TempDir();
        var folder = new TaskFolder(tmp.Path, 1, "alpha");

        await folder.EnsureExistsAsync(Today, TestContext.Current.CancellationToken);

        Directory.Exists(folder.Path).Should().BeTrue();
        File.Exists(Path.Combine(folder.Path, "index.md")).Should().BeTrue();
        File.Exists(Path.Combine(folder.Path, "description.md")).Should().BeTrue();
        File.Exists(Path.Combine(folder.Path, "progress.md")).Should().BeTrue();

        var index = await File.ReadAllTextAsync(Path.Combine(folder.Path, "index.md"), TestContext.Current.CancellationToken);
        index.Should().Contain("# Task index").And.Contain("description.md").And.Contain("progress.md").And.Contain("2026-05-07");
        var progress = await File.ReadAllTextAsync(Path.Combine(folder.Path, "progress.md"), TestContext.Current.CancellationToken);
        progress.Should().Contain("## 2026-05-07");
    }

