    [Fact]
    public async Task CopyArtifacts_retains_destination_files_not_present_in_source()
    {
        // Pin orphan-retention semantics: a fork that was already running picks up extra
        // artifacts (e.g. progress.md edits, ad-hoc notes). Re-copying from a now-stale source
        // must NOT delete those — the source-only-copy plus per-name overwrite is intentional.
        using var tmp = new TempDir();
        var src = new TaskFolder(tmp.Path, 1, "source");
        await src.EnsureExistsAsync(Today, TestContext.Current.CancellationToken);
        await src.WriteScaffoldedDescriptionAsync("# Source description\n", TestContext.Current.CancellationToken);

        var dst = new TaskFolder(tmp.Path, 2, "fork");
        await dst.EnsureExistsAsync(Today, TestContext.Current.CancellationToken);
        // A file that exists ONLY in destination — must survive the copy.
        var orphanPath = Path.Combine(dst.Path, "orphan.md");
        await File.WriteAllTextAsync(orphanPath, "# fork-only notes", TestContext.Current.CancellationToken);

        await src.CopyArtifactsToAsync(dst, TestContext.Current.CancellationToken);

        File.Exists(orphanPath).Should().BeTrue("destination-only files must not be deleted");
        (await File.ReadAllTextAsync(orphanPath, TestContext.Current.CancellationToken)).Should().Be("# fork-only notes");
        // Sanity: the source files still arrived.
        File.Exists(Path.Combine(dst.Path, "description.md")).Should().BeTrue();
    }

    [Fact]
    public async Task CopyArtifacts_is_noop_when_source_folder_is_missing()
    {
        using var tmp = new TempDir();
        var src = new TaskFolder(tmp.Path, 1, "source"); // never created
        var dst = new TaskFolder(tmp.Path, 2, "fork");

        await src.CopyArtifactsToAsync(dst, TestContext.Current.CancellationToken);

        Directory.Exists(dst.Path).Should().BeTrue(); // dest still gets created
        Directory.EnumerateFiles(dst.Path).Should().BeEmpty();
    }

    private sealed class TempDir : IDisposable
    {
        public string Path { get; }

        public TempDir()
        {
            Path = System.IO.Path.Combine(System.IO.Path.GetTempPath(), $"cp-tasks-{Guid.NewGuid():N}");
            Directory.CreateDirectory(Path);
        }

        public void Dispose()
        {
            try { Directory.Delete(Path, recursive: true); } catch { /* best-effort */ }
        }
    }
}
